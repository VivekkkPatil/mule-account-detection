import pandas as pd
import json
from datetime import datetime
from pathlib import Path
from src import config


AUDIT_LOG_PATH = config.OUTPUTS_DIR / "audit_trail.csv"
SAR_DIR = config.OUTPUTS_DIR / "SAR_reports"


def _init_audit_log():
    """Create audit log CSV if it doesn't exist."""
    if not AUDIT_LOG_PATH.exists():
        pd.DataFrame(columns=[
            "timestamp", "account_idx", "action",
            "risk_tier", "risk_score", "investigator",
            "reason", "status"
        ]).to_csv(AUDIT_LOG_PATH, index=False)


def log_action(account_idx: int, action: str, risk_tier: str,
               risk_score: float, investigator: str = "System",
               reason: str = ""):
    """
    Log an investigator action to the audit trail CSV.

    Actions: FREEZE, FLAG_FOR_REVIEW, CLEAR, ESCALATE, MONITOR
    """
    _init_audit_log()

    new_row = {
        "timestamp": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        "account_idx": account_idx,
        "action": action,
        "risk_tier": risk_tier,
        "risk_score": round(risk_score, 4),
        "investigator": investigator,
        "reason": reason,
        "status": "PENDING" if action in ["FREEZE", "ESCALATE"] else "CLOSED"
    }

    existing = pd.read_csv(AUDIT_LOG_PATH)
    updated = pd.concat([existing, pd.DataFrame([new_row])], ignore_index=True)
    updated.to_csv(AUDIT_LOG_PATH, index=False)

    return new_row


