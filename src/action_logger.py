def get_audit_trail() -> pd.DataFrame:
    """Load and return the full audit trail."""
    _init_audit_log()
    return pd.read_csv(AUDIT_LOG_PATH)


def get_account_status(account_idx: int) -> str:
    """Get the latest action status for an account."""
    _init_audit_log()
    df = pd.read_csv(AUDIT_LOG_PATH)
    account_logs = df[df["account_idx"] == account_idx]
    if account_logs.empty:
        return "NO_ACTION"
    return account_logs.iloc[-1]["action"]